"""
Phase 3 gate: validation table and per-model transform selection (seed 1).

Reads only validation metrics: results/runs/<model>_<track>_h<h>_<condition>_s1.json
and, as a reference row on the same validation windows, the persistence
baseline (results/baselines/<track>_h<h>.json).

Selection rule (author's, fixed before the runs):
  For each (model, track, horizon), choose the condition with the lowest
  validation MAE in original price units. If several conditions are within
  1% of that lowest MAE, choose the simplest of them in the order
  minmax < log_return < revin.

Writes results/selection/validation_table.md and results/selection/selection.json.
Also writes the duplicate-rule sensitivity comparison (validation) to
results/sensitivity/duplicate_last/comparison_val.md when those runs exist.

    python scripts/select_transforms.py
"""

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from src.utils.provenance import provenance  # noqa: E402

MODELS = ["lstm", "gru", "tsmixer", "patchtst", "tft"]
CONDITIONS = ["minmax", "log_return", "revin"]     # simplicity order for the tie-break
TRACKS, HORIZONS = ["sudan", "global"], [1, 7, 30]
TIE = 0.01
RULE = ("Lowest validation MAE in original price units per (model, track, horizon); "
        "conditions within 1% of the lowest MAE are tied and the simplest is chosen, "
        "in the order minmax < log_return < revin. Seed 1 only.")
NOISE_NOTE = ("Sudan validation has only 223 / 217 / 194 windows (h = 1 / 7 / 30), all from one "
              "7-month period (2021-03 → 2021-10) after the 404-day gap, so the Sudan selection is noisy; "
              "global validation has 915 / 909 / 886 windows (2017-09 → 2021-05).")
RUNS = Path("results/runs")
SENS = Path("results/sensitivity/duplicate_last/runs")
MAE_REL, MAPE_ABS = 0.05, 0.1   # 'material' for the sensitivity check (same as Phase 2)


def load(path: Path) -> dict | None:
    return json.loads(path.read_text()) if path.exists() else None


def choose(maes: dict) -> tuple[str | None, list]:
    avail = {c: m for c, m in maes.items() if m is not None}
    if not avail:
        return None, []
    best = min(avail.values())
    tied = [c for c in CONDITIONS if c in avail and avail[c] <= best * (1 + TIE)]
    return tied[0], tied


def main():
    out_dir = Path("results/selection")
    out_dir.mkdir(parents=True, exist_ok=True)
    selection, missing = {}, []
    lines = ["# Phase 3 gate: validation results, seed 1 (generated by scripts/select_transforms.py)", "",
             f"**Selection rule.** {RULE}", "", f"**Caveat.** {NOISE_NOTE}", "",
             "Validation only: no test window has been predicted for any run in this table. "
             "MAE in price units (SDG/g Sudan, USD/oz global). `epochs` = epochs trained "
             "(max 100, early-stopping patience 10 on validation MAE in model space). "
             "★ = selected; † = within 1% of the best (tie).", ""]
    for track in TRACKS:
        for h in HORIZONS:
            base = load(Path(f"results/baselines/{track}_h{h}.json"))
            lines += [f"## {track} h={h}", "",
                      "| model | MinMax MAE | MinMax MAPE % | log-return MAE | log-return MAPE % | RevIN MAE | RevIN MAPE % | epochs (mm / lr / rv) | selected |",
                      "|---|---:|---:|---:|---:|---:|---:|---|---|"]
            n_val = None
            for model in MODELS + ["ensemble"]:
                cells, maes, epochs = [], {}, []
                for c in CONDITIONS:
                    if model == "ensemble":
                        r = load(Path(f"results/ensembles/{track}_h{h}_{c}_s1.json"))
                    else:
                        r = load(RUNS / f"{model}_{track}_h{h}_{c}_s1.json")
                    v = r["metrics"]["val"] if r else None
                    if v is None:
                        if model != "ensemble":
                            missing.append(f"{model}_{track}_h{h}_{c}_s1")
                        maes[c] = None
                        cells += ["—", "—"]
                        epochs.append("—")
                        continue
                    n_val = n_val or v["n_windows"]
                    assert v["n_windows"] == n_val, "validation windows differ between conditions"
                    maes[c] = v["mae"]
                    cells += [f"{v['mae']:.2f}", f"{v['mape']:.2f}"]
                    epochs.append(str(r.get("epochs_trained", "—")) if model != "ensemble" else "—")
                chosen, tied = choose(maes)
                if model != "ensemble" and chosen and all(m is not None for m in maes.values()):
                    selection[f"{model}_{track}_h{h}"] = {
                        "model": model, "track": track, "horizon": h, "condition": chosen,
                        "tied_within_1pct": tied, "val_mae": maes, "n_val_windows": n_val}
                for i, c in enumerate(CONDITIONS):
                    if maes.get(c) is None:
                        continue
                    mark = "★" if c == chosen and model != "ensemble" else ("†" if c in tied and len(tied) > 1 else "")
                    cells[2 * i] += f" {mark}".rstrip()
                label = "ensemble (top-2, val-selected per condition)" if model == "ensemble" else model
                sel = (chosen or "—") if model != "ensemble" else "n/a"
                lines.append(f"| {label} | " + " | ".join(cells) + f" | {' / '.join(epochs)} | {sel} |")
            if base:
                pv = base["baselines"]["persistence"]["val"]
                assert n_val is None or pv["n_windows"] == n_val, "persistence evaluated on different windows"
                lines.append(f"| *persistence (reference)* | {pv['mae']:.2f} | {pv['mape']:.2f} | "
                             f"{pv['mae']:.2f} | {pv['mape']:.2f} | {pv['mae']:.2f} | {pv['mape']:.2f} | — | — |")
            lines += ["", f"Validation windows: {n_val}", ""]

    # Count of chosen conditions
    counts = {c: sum(1 for s in selection.values() if s["condition"] == c) for c in CONDITIONS}
    lines += ["## Selected condition counts", "",
              " · ".join(f"{c}: {n}" for c, n in counts.items()) + f" (of {len(selection)} model × track × horizon cells)", ""]
    if missing:
        lines += [f"**Missing runs ({len(missing)}):** " + ", ".join(missing), ""]
    (out_dir / "validation_table.md").write_text("\n".join(lines) + "\n")
    (out_dir / "selection.json").write_text(json.dumps(
        {"rule": RULE, "tie_tolerance": TIE, "simplicity_order": CONDITIONS, "caveat": NOISE_NOTE,
         "seed": 1, "provenance": provenance({"mlflow": {"protocol": "v2"}}),
         "selection": selection, "missing_runs": missing}, indent=2))
    print("\n".join(lines))
    sensitivity_val()


def sensitivity_val():
    """Duplicate rule 'last' vs 'first' for Sudan LSTM/GRU MinMax seed 1, validation metrics."""
    if not SENS.exists():
        return
    rows = ["# Duplicate-date rule sensitivity, neural models, validation (generated by scripts/select_transforms.py)", "",
            f"Sudan, MinMax, seed 1. Material = relative MAE change > {100 * MAE_REL:.0f}% or |ΔMAPE| ≥ {MAPE_ABS} pp. "
            "Test comparison follows once the MinMax seed-1 models are scored on test (after the gate).", "",
            "| model | h | val MAE first | val MAE last | ΔMAE % | val MAPE first | val MAPE last | ΔMAPE pp | epochs first / last | material |",
            "|---|---:|---:|---:|---:|---:|---:|---:|---|---|"]
    out = []
    for model in ("lstm", "gru"):
        for h in HORIZONS:
            a = load(RUNS / f"{model}_sudan_h{h}_minmax_s1.json")
            b = load(SENS / f"{model}_sudan_h{h}_minmax_s1.json")
            if not (a and b):
                continue
            va, vb = a["metrics"]["val"], b["metrics"]["val"]
            rel = (vb["mae"] - va["mae"]) / va["mae"]
            d = vb["mape"] - va["mape"]
            mat = abs(rel) > MAE_REL or abs(d) >= MAPE_ABS
            out.append({"model": model, "h": h, "val_mae_first": va["mae"], "val_mae_last": vb["mae"],
                        "rel_change": rel, "mape_change_pp": d, "material": mat})
            rows.append(f"| {model} | {h} | {va['mae']:.2f} | {vb['mae']:.2f} | {100 * rel:+.2f} | {va['mape']:.2f} | "
                        f"{vb['mape']:.2f} | {d:+.3f} | {a['epochs_trained']} / {b['epochs_trained']} | {'yes' if mat else 'no'} |")
    d = Path("results/sensitivity/duplicate_last")
    (d / "comparison_val.md").write_text("\n".join(rows) + "\n")
    (d / "comparison_val.json").write_text(json.dumps({"rows": out}, indent=2))


if __name__ == "__main__":
    main()
