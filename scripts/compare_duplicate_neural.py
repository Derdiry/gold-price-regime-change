"""
Duplicate-date rule sensitivity for the neural models (Sudan LSTM and GRU).

Compares "keep first" (the main runs, results/runs/) with "keep last" (the
sensitivity runs, results/sensitivity/duplicate_last/runs/), under each
model's validation-selected condition, seeds 1-3, on validation and test.
Both rules use identical windows (all multi-row dates are in training rows).

Decision rule (fixed before looking at the results): the rule "matters" for
a (model, horizon, split) if |mean_last − mean_first| > 2 × pooled seed SD,
pooled SD = sqrt((sd_first² + sd_last²) / 2), on MAE in price units.

Also reports the stage-1 MinMax seed-1 comparison on test.
Writes results/sensitivity/duplicate_last/comparison_neural.{md,json}.
"""

import json
from pathlib import Path

import numpy as np

SEL = json.loads(Path("results/selection/selection.json").read_text())["selection"]
MAIN, SENS = Path("results/runs"), Path("results/sensitivity/duplicate_last/runs")
OUT = Path("results/sensitivity/duplicate_last")


def mae(path, split):
    return json.loads(path.read_text())["metrics"][split]["mae"]


def main():
    rows, lines = [], ["# Duplicate-date rule: neural models (generated by scripts/compare_duplicate_neural.py)", "",
                       "Sudan, each model's selected condition, seeds 1–3. \"Matters\" = |Δ mean| > 2 × pooled seed SD "
                       "(fixed in advance). MAE in SDG/g.", "",
                       "| model | h | condition | split | MAE keep-first (mean ± sd) | MAE keep-last (mean ± sd) | Δ mean | pooled seed SD | |Δ| / SD | matters |",
                       "|---|---:|---|---|---:|---:|---:|---:|---:|---|"]
    for model in ("lstm", "gru"):
        for h in (1, 7, 30):
            cond = SEL[f"{model}_sudan_h{h}"]["condition"]
            for split in ("val", "test"):
                a = np.array([mae(MAIN / f"{model}_sudan_h{h}_{cond}_s{s}.json", split) for s in (1, 2, 3)])
                b = np.array([mae(SENS / f"{model}_sudan_h{h}_{cond}_s{s}.json", split) for s in (1, 2, 3)])
                sd = float(np.sqrt((a.std(ddof=1) ** 2 + b.std(ddof=1) ** 2) / 2))
                diff = float(b.mean() - a.mean())
                ratio = abs(diff) / sd if sd > 0 else float("inf")
                matters = ratio > 2
                rows.append({"model": model, "h": h, "condition": cond, "split": split, "first": a.tolist(),
                             "last": b.tolist(), "diff_mean": diff, "pooled_sd": sd, "ratio": ratio, "matters": matters})
                lines.append(f"| {model} | {h} | {cond} | {split} | {a.mean():.2f} ± {a.std(ddof=1):.2f} | "
                             f"{b.mean():.2f} ± {b.std(ddof=1):.2f} | {diff:+.2f} | {sd:.2f} | {ratio:.2f} | {'yes' if matters else 'no'} |")
    n = sum(r["matters"] for r in rows)
    lines += ["", f"**The rule matters in {n} of {len(rows)} (model, horizon, split) cells.**", "",
              "## Stage 1, MinMax, seed 1 (no seed spread available)", "",
              "| model | h | val MAE first | val MAE last | test MAE first | test MAE last | test Δ % |", "|---|---:|---:|---:|---:|---:|---:|"]
    mm = []
    for model in ("lstm", "gru"):
        for h in (1, 7, 30):
            k = f"{model}_sudan_h{h}_minmax_s1.json"
            va, vb, ta, tb = mae(MAIN / k, "val"), mae(SENS / k, "val"), mae(MAIN / k, "test"), mae(SENS / k, "test")
            mm.append({"model": model, "h": h, "val_first": va, "val_last": vb, "test_first": ta, "test_last": tb})
            lines.append(f"| {model} | {h} | {va:.2f} | {vb:.2f} | {ta:.2f} | {tb:.2f} | {100 * (tb - ta) / ta:+.2f} |")
    (OUT / "comparison_neural.md").write_text("\n".join(lines) + "\n")
    (OUT / "comparison_neural.json").write_text(json.dumps({"rule": "matters if |diff of means| > 2 * pooled seed SD",
                                                            "selected_condition": rows, "minmax_seed1": mm}, indent=2))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
