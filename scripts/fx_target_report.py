"""
Phase 4.7: rebuild price from SDG/USD forecasts, select conditions on
validation, and compare with persistence and with direct price forecasting.

Rules: results/fx_target/PREREGISTRATION.md (must be committed before either step).

  select   seed-1 validation only -> results/fx_target/selection/{selection.json, validation_table.md}
  report   test evaluation        -> results/fx_target/{fx_results.json, fx_table.md, dm_tests.csv},
                                      results/fx_target/ensembles/selected_sudan_h<h>_s<seed>.json

Main reconstruction (forecast):   P_t * fx_hat / fx_t
Diagnostic (uses future intl):    P_t * (fx_hat / fx_t) * (intl_{t+k} / intl_t)   -- not a forecast

    python scripts/fx_target_report.py select
    python scripts/fx_target_report.py report
"""

import argparse
import json
import subprocess
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "scripts"))
from src.data.dataset import make_dataset  # noqa: E402
from src.data.features import SUDAN_FEATURE_COLS  # noqa: E402
from src.data.fetchers import load_config  # noqa: E402
from src.data.pipeline import build_sudan  # noqa: E402
from src.evaluation.metrics import compute_all_metrics  # noqa: E402
from src.evaluation.stats import diebold_mariano, holm, mase_vs_persistence  # noqa: E402
from src.models.ensemble import apply_ensemble, fit_validation_ensemble  # noqa: E402
from src.utils.provenance import provenance  # noqa: E402

HORIZONS, SEEDS = [1, 7, 30], [1, 2, 3]
MODELS = ["lstm", "gru", "tsmixer", "patchtst", "tft"]
CONDITIONS = ["minmax", "log_return", "revin"]
TIE, ALPHA, LOSSES = 0.01, 0.05, ["squared", "absolute"]
FX_PREDS, PRICE_PREDS = Path("logs/v2/fx_target/preds"), Path("logs/v2/preds")
FX_RUNS = Path("results/fx_target/runs")
OUT = Path("results/fx_target")
PREREG = OUT / "PREREGISTRATION.md"


def require_committed_preregistration():
    rel = str(PREREG)
    tracked = subprocess.run(["git", "ls-files", "--error-unmatch", rel], cwd=ROOT, capture_output=True).returncode == 0
    clean = not subprocess.run(["git", "status", "--porcelain", "--", rel], cwd=ROOT, capture_output=True, text=True).stdout.strip()
    if not (tracked and clean):
        sys.exit(f"{rel} must be committed (and unchanged) before this step.")
    return subprocess.run(["git", "log", "-1", "--format=%H", "--", rel], cwd=ROOT, capture_output=True, text=True).stdout.strip()


def windows(cfg):
    """Per (h, split): price/fx/intl at the origin and the targets, on the Phase 3 windows."""
    df = build_sudan(cfg)
    price, fx, intl = (df[c].to_numpy(float) for c in (cfg["data"]["target_col"], "fx_rate", "intl_price_usd"))
    out = {}
    for h in HORIZONS:
        sp_p, _, _, _ = make_dataset(df, cfg, "sudan", h, SUDAN_FEATURE_COLS, cfg["data"]["target_col"], save=False)
        sp_f, _, _, _ = make_dataset(df, cfg, "sudan", h, SUDAN_FEATURE_COLS, "fx_rate", save=False)
        for s in ("val", "test"):
            assert (sp_p[f"origin_{s}"] == sp_f[f"origin_{s}"]).all(), "FX and price windows differ"
            pos = df.index.get_indexer(pd.to_datetime(sp_p[f"origin_{s}"]))
            fut = np.stack([pos + 1 + k for k in range(h)], 1)
            out[(h, s)] = {"P": price[pos], "fx": fx[pos], "intl": intl[pos], "y": price[fut],
                           "y_fx": fx[fut], "intl_fut": intl[fut]}
            assert np.allclose(out[(h, s)]["y_fx"], sp_f[f"yraw_{s}"])
    return out


def rebuild(fx_hat, w, oracle=False):
    p = w["P"][:, None] * fx_hat / w["fx"][:, None]
    return p * w["intl_fut"] / w["intl"][:, None] if oracle else p


def load(key, split):
    z = np.load(FX_PREDS / f"{key}.npz")
    if f"{split}_pred" not in z:
        raise RuntimeError(f"{key} has no {split} predictions")
    return z[f"{split}_pred"]


def select(cfg):
    require_committed_preregistration()
    W = windows(cfg)
    sel, lines = {}, ["# FX target: validation selection, seed 1 (generated by scripts/fx_target_report.py select)", "",
                      "Validation MAE of the rebuilt price P_t·fx̂/fx_t (SDG/g); FX MAE in SDG/USD. ★ selected (lowest rebuilt-price "
                      "MAE; within 1% the simplest of minmax < log_return < revin).", ""]
    for h in HORIZONS:
        w = W[(h, "val")]
        pers = float(np.abs(w["y"] - w["P"][:, None]).mean())
        lines += [f"## h={h}", "", "| model | " + " | ".join(f"{c} price MAE | {c} FX MAE" for c in CONDITIONS) + " | selected | direct-price val MAE (Phase 3 selected) |",
                  "|---|" + "---:|---:|" * 3 + "---|---:|"]
        price_sel = json.loads(Path("results/selection/selection.json").read_text())["selection"]
        for m in MODELS:
            maes, cells = {}, []
            for c in CONDITIONS:
                fv = load(f"{m}_sudan_h{h}_{c}_s1", "val")
                maes[c] = float(np.abs(w["y"] - rebuild(fv, w)).mean())
                cells += [f"{maes[c]:.2f}", f"{np.abs(w['y_fx'] - fv).mean():.3f}"]
            best = min(maes.values())
            tied = [c for c in CONDITIONS if maes[c] <= best * (1 + TIE)]
            sel[f"{m}_h{h}"] = {"model": m, "horizon": h, "condition": tied[0], "tied_within_1pct": tied, "val_price_mae": maes}
            pc = price_sel[f"{m}_sudan_h{h}"]
            lines.append(f"| {m} | " + " | ".join(cells) + f" | {tied[0]} | {pc['val_mae'][pc['condition']]:.2f} ({pc['condition']}) |")
        lines += [f"| *persistence* | {pers:.2f} | — | {pers:.2f} | — | {pers:.2f} | — | — | {pers:.2f} |", ""]
    (OUT / "selection").mkdir(parents=True, exist_ok=True)
    (OUT / "selection/selection.json").write_text(json.dumps(
        {"rule": "lowest validation MAE of the rebuilt price; 1% tie -> minmax < log_return < revin; seed 1",
         "provenance": provenance(cfg), "selection": sel}, indent=2))
    (OUT / "selection/validation_table.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


def score(y, f, last, pers, h, mask=None):
    if mask is not None:
        from posthoc_observed_days import score as masked
        return masked(y, f, last, pers, h, mask)
    m = compute_all_metrics(y, f, last)
    out = {"mae": m["mae"], "rmse": m["rmse"], "mape": m["mape"], "da_nonzero": m["directional_accuracy_nonzero"],
           "mase": mase_vs_persistence(y, f, pers), "n": m["n_windows"]}
    for loss in LOSSES:
        out[f"dm_{loss}"] = diebold_mariano(y, f, pers, h, loss)
    return out


def verdict(dms, pkey, words):
    if all(d["dm_hln"] < 0 and d[pkey] < ALPHA for d in dms):
        return words[0]
    if all(d["dm_hln"] > 0 and d[pkey] < ALPHA for d in dms):
        return words[1]
    return "no significant difference"


def report(cfg):
    prereg_commit = require_committed_preregistration()
    from posthoc_observed_days import observed_masks
    S1 = observed_masks(cfg)
    W = windows(cfg)
    sel = json.loads((OUT / "selection/selection.json").read_text())["selection"]
    psel = json.loads(Path("results/selection/selection.json").read_text())["selection"]
    results = {}
    for h in HORIZONS:
        wv, wt = W[(h, "val")], W[(h, "test")]
        b = np.load(PRICE_PREDS / "baselines" / f"sudan_h{h}.npz")
        assert np.allclose(b["y_test"], wt["y"]) and np.allclose(b["last_test"], wt["P"])
        pers = b["persistence_test"]
        fx_val, fx_test, pr_val, pr_test = ({s: {} for s in SEEDS} for _ in range(4))
        cfgs = {}
        for m in MODELS:
            c, pc = sel[f"{m}_h{h}"]["condition"], psel[f"{m}_sudan_h{h}"]["condition"]
            for s in SEEDS:
                key = f"{m}_sudan_h{h}_{c}_s{s}"
                rec = json.loads((FX_RUNS / f"{key}.json").read_text())
                ft = load(key, "test")
                assert np.isclose(np.abs(wt["y_fx"] - ft).mean(), rec["metrics"]["test"]["mae"], rtol=1e-6), key
                fx_val[s][m], fx_test[s][m] = rebuild(load(key, "val"), wv), rebuild(ft, wt)
                fx_test[s][m + "_oracle"] = rebuild(ft, wt, oracle=True)
                fx_test[s][m + "_fxmae"] = float(np.abs(wt["y_fx"] - ft).mean())
                z = np.load(PRICE_PREDS / f"{m}_sudan_h{h}_{pc}_s{s}.npz")
                pr_val[s][m], pr_test[s][m] = z["val_pred"], z["test_pred"]
            cfgs[m] = {"fx_condition": c, "direct_condition": pc}
        # Validation-selected ensembles (FX route, and the Phase 3 direct-price one)
        for s in SEEDS:
            e = fit_validation_ensemble({m: fx_val[s][m] for m in MODELS}, wv["y"], top_n=2)
            fx_test[s]["ensemble"] = apply_ensemble({m: fx_test[s][m] for m in MODELS}, e)
            fx_test[s]["ensemble_oracle"] = apply_ensemble({m: fx_test[s][m + "_oracle"] for m in MODELS}, e)
            fx_test[s]["ensemble_fxmae"] = float("nan")
            (OUT / "ensembles").mkdir(parents=True, exist_ok=True)
            (OUT / "ensembles" / f"selected_sudan_h{h}_s{s}.json").write_text(json.dumps(
                {"route": "fx_target", "horizon": h, "seed": s, **e,
                 "val_price_mae": float(np.abs(wv["y"] - apply_ensemble({m: fx_val[s][m] for m in MODELS}, e)).mean()),
                 "provenance": provenance(cfg)}, indent=2))
            pe = json.loads(Path(f"results/ensembles/selected_sudan_h{h}_s{s}.json").read_text())
            pr_test[s]["ensemble"] = apply_ensemble({r.split("_sudan_")[0]: np.load(PRICE_PREDS / f"{r}.npz")["test_pred"]
                                                     for r in pe["member_records"]}, pe)
            fx_test[s]["ensemble_members"] = e["selected"]
        cfgs["ensemble"] = {"fx_condition": "selected members", "direct_condition": "selected members"}
        cell = {}
        for name in [*MODELS, "ensemble"]:
            seeds = []
            for s in SEEDS:
                f, d = fx_test[s][name], pr_test[s][name]
                sc = {"fx": score(wt["y"], f, wt["P"], pers, h), "direct": score(wt["y"], d, wt["P"], pers, h),
                      "fx_S1": score(wt["y"], f, wt["P"], pers, h, S1[h]["obs"]),
                      "oracle_diagnostic": {"mae": float(np.abs(wt["y"] - fx_test[s][name + "_oracle"]).mean()),
                                            "mase": mase_vs_persistence(wt["y"], fx_test[s][name + "_oracle"], pers)},
                      "fx_units_mae": fx_test[s][name + "_fxmae"]}
                sc["vs_direct"] = {loss: diebold_mariano(wt["y"], f, d, h, loss) for loss in LOSSES}
                if name == "ensemble":
                    sc["members"] = fx_test[s]["ensemble_members"]
                seeds.append(sc)
            cell[name] = {**cfgs[name], "seeds": seeds}
        results[h] = cell

    # Holm per comparison and loss over the 54 seed-level tests
    for comp, getter in (("persistence", lambda sc, loss: sc["fx"][f"dm_{loss}"]), ("direct", lambda sc, loss: sc["vs_direct"][loss])):
        for loss in LOSSES:
            refs = [sc for cell in results.values() for c in cell.values() for sc in c["seeds"]]
            for sc, p in zip(refs, holm([getter(sc, loss)["p_value"] for sc in refs])):
                getter(sc, loss)["p_holm"] = p
    for cell in results.values():
        for c in cell.values():
            for loss in LOSSES:
                for pk, suf in (("p_value", ""), ("p_holm", "_holm")):
                    c[f"verdict_vs_persistence_{loss}{suf}"] = verdict([sc["fx"][f"dm_{loss}"] for sc in c["seeds"]], pk,
                                                                        ("beats persistence", "worse"))
                    c[f"verdict_vs_direct_{loss}{suf}"] = verdict([sc["vs_direct"][loss] for sc in c["seeds"]], pk,
                                                                  ("FX route better", "FX route worse"))
    cells = [c for cell in results.values() for c in cell.values()]
    nb = sum(c["verdict_vs_direct_absolute"] == "FX route better" for c in cells)
    nw = sum(c["verdict_vs_direct_absolute"] == "FX route worse" for c in cells)
    answer = ("the FX route improves on direct price forecasting" if nb >= 10 and nw == 0 else
              "the FX route is worse" if nw >= 10 and nb == 0 else "no consistent difference")
    summary = {"n_cells": len(cells), "fx_better_abs": nb, "fx_worse_abs": nw, "answer": answer,
               "beats_persistence_abs": sum(c["verdict_vs_persistence_absolute"] == "beats persistence" for c in cells),
               "worse_than_persistence_abs": sum(c["verdict_vs_persistence_absolute"] == "worse" for c in cells)}
    (OUT / "fx_results.json").write_text(json.dumps(
        {"provenance": provenance(cfg), "preregistration_commit": prereg_commit, "preregistration_text": PREREG.read_text(),
         "summary": summary, "results": {f"sudan_h{h}": v for h, v in results.items()}}, indent=2, default=float))
    rows = [{"h": h, "config": n, "seed": s, "comparison": comp, "loss": loss, "dm_hln": d["dm_hln"], "p_value": d["p_value"],
             "p_holm": d["p_holm"], "n": d["n"]}
            for h, cell in results.items() for n, c in cell.items() for s, sc in zip(SEEDS, c["seeds"]) for loss in LOSSES
            for comp, d in (("vs_persistence", sc["fx"][f"dm_{loss}"]), ("vs_direct", sc["vs_direct"][loss]))]
    pd.DataFrame(rows).to_csv(OUT / "dm_tests.csv", index=False)
    write_markdown(results, summary, prereg_commit)


def ms(v, fmt="{:.2f}"):
    v = np.asarray(v, float)
    v = v[~np.isnan(v)]
    return "—" if not len(v) else f"{fmt.format(v.mean())} ± {fmt.format(v.std(ddof=1))}" if len(v) > 1 else fmt.format(v[0])


def write_markdown(results, summary, prereg_commit):
    L = ["# FX as the target (generated by scripts/fx_target_report.py report)", "",
         f"Rules fixed in `{PREREG}` (commit `{prereg_commit[:7]}`) before training. Price rebuilt as P_t·fx̂/fx_t "
         "(international price held at its origin value). Metrics in SDG/g on the Phase 3 test windows; mean ± std over seeds 1–3. "
         "DM p for seeds 1/2/3 with sign (− = the FX route has lower loss). Verdicts need the sign to agree and p < 0.05 in all three seeds.", "",
         f"**Summary (absolute loss, FX route vs direct price, {summary['n_cells']} cells):** {summary['fx_better_abs']} FX route better, "
         f"{summary['fx_worse_abs']} FX route worse → **{summary['answer']}**. Vs persistence (absolute): "
         f"{summary['beats_persistence_abs']} beat, {summary['worse_than_persistence_abs']} worse.", "",
         "*Oracle column: diagnostic that uses the realised future international price. Not a forecast.*", ""]
    for h, cell in results.items():
        L += [f"## h={h}", "",
              "| configuration | FX cond. | direct cond. | FX-route MAE | direct MAE | FX-route MASE | direct MASE | FX MAE (SDG/USD) | "
              "p vs direct abs | verdict vs direct abs / sq | verdict vs persistence abs / sq | S1 MASE | *oracle MASE (diagnostic)* |",
              "|---|---|---|---:|---:|---:|---:|---:|---|---|---|---:|---:|"]
        for n, c in cell.items():
            S = c["seeds"]
            pv = "/".join("%.3f%s" % (sc["vs_direct"]["absolute"]["p_value"], "−" if sc["vs_direct"]["absolute"]["dm_hln"] < 0 else "+") for sc in S)
            L.append(f"| {n} | {c['fx_condition']} | {c['direct_condition']} | {ms([s['fx']['mae'] for s in S])} | {ms([s['direct']['mae'] for s in S])} | "
                     f"{ms([s['fx']['mase'] for s in S], '{:.3f}')} | {ms([s['direct']['mase'] for s in S], '{:.3f}')} | "
                     f"{ms([s['fx_units_mae'] for s in S], '{:.3f}')} | {pv} | {c['verdict_vs_direct_absolute']} / {c['verdict_vs_direct_squared']} | "
                     f"{c['verdict_vs_persistence_absolute']} / {c['verdict_vs_persistence_squared']} | {ms([s['fx_S1']['mase'] for s in S], '{:.3f}')} | "
                     f"*{ms([s['oracle_diagnostic']['mase'] for s in S], '{:.3f}')}* |")
        L.append("")
    (OUT / "fx_table.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("step", choices=["select", "report"])
    args = ap.parse_args()
    cfg = load_config("configs/model_config.yaml")
    select(cfg) if args.step == "select" else report(cfg)


if __name__ == "__main__":
    main()
