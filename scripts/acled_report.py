"""
Phase 4.3 report: ACLED conflict features (lags 1-3), with vs without, TFT and
LSTM, main split (seeds 1-3) and rolling folds 1-5 (selected lag, seed 1).

Rules: results/acled/PREREGISTRATION.md (must be committed).

    python scripts/acled_report.py select   # lag for the rolling check, validation only
    python scripts/acled_report.py check    # recompute the saved selection (read-only)
    python scripts/acled_report.py report   # verdicts

select -> results/acled/selection/{lag_selection.json, lag_selection.md}
report -> results/acled/{acled_results.json, acled_table.md, dm_tests.csv}
"""

import argparse
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
from paired_common import (HORIZONS, LOSSES, ROOT, SEEDS, add_holm, baseline, load_run, ms, paired,  # noqa: E402
                           pfmt, require_committed, score, verdict)

sys.path.insert(0, str(ROOT))
from src.data.fetchers import load_config  # noqa: E402
from src.utils.provenance import provenance  # noqa: E402

MODELS, LAGS, FOLDS = ["tft", "lstm"], [1, 2, 3], [1, 2, 3, 4, 5]
OUT = ROOT / "results/acled"
PREREG = OUT / "PREREGISTRATION.md"
SELECTION = OUT / "selection/lag_selection.json"
WORDS = ("conflict features help", "conflict features hurt")


def conflict_cols(k):
    return [f"pv_events_lag{k}m", f"pv_fatalities_lag{k}m"]


def vs_pers(scores):
    """DM verdict against persistence on absolute loss over the given seeds (descriptive column)."""
    return verdict([sc["vs_persistence"]["absolute"] for sc in scores], "p_value", ("beats persistence", "worse"))


def selection_rows(before_test):
    """Validation MAE with/without per (lag, model, h, seed); before_test asserts no test prediction exists yet."""
    sel = json.loads((ROOT / "results/selection/selection.json").read_text())["selection"]
    rows = []
    for k in LAGS:
        for m in MODELS:
            for h in HORIZONS:
                c = sel[f"{m}_sudan_h{h}"]["condition"]
                for s in SEEDS:
                    key = f"{m}_sudan_h{h}_{c}_s{s}"
                    w = json.loads((OUT / f"main/lag{k}/runs/{key}.json").read_text())
                    if before_test:
                        has_test = "test_pred" in np.load(ROOT / f"logs/v2/acled/main/lag{k}/preds/{key}.npz")
                        assert w["metrics"]["test"] is None and not has_test, \
                            f"{key}: lag {k} run already has test predictions; selection must come first"
                    assert w["feature_cols"][-2:] == conflict_cols(k), key
                    wo = json.loads((ROOT / f"results/runs/{key}.json").read_text())
                    rows.append({"lag": k, "model": m, "h": h, "seed": s, "val_mae_with": w["metrics"]["val"]["mae"],
                                 "val_mae_without": wo["metrics"]["val"]["mae"]})
    df = pd.DataFrame(rows).assign(ratio=lambda d: d.val_mae_with / d.val_mae_without)
    mean = df.groupby("lag")["ratio"].mean()
    best = int(mean.index[np.flatnonzero(mean.to_numpy() == mean.min())[0]])   # exact ties -> shorter lag
    return rows, mean, best


def check():
    """Recompute the saved lag selection from the validation metrics (no writes; test runs may exist by now)."""
    rows, mean, best = selection_rows(before_test=False)
    saved = json.loads(SELECTION.read_text())
    assert saved["selected_lag"] == best and saved["rows"] == rows, "lag selection does not reproduce"
    assert all(saved["mean_ratio"][str(k)] == float(v) for k, v in mean.items()), "mean ratios do not reproduce"
    print(f"lag selection reproduces: lag {best}, mean ratios " + ", ".join(f"{k}: {v:.4f}" for k, v in mean.items()))


def select():
    prereg_commit = require_committed(PREREG)
    cfg = load_config(str(ROOT / "configs/model_config.yaml"))
    rows, mean, best = selection_rows(before_test=True)
    SELECTION.parent.mkdir(parents=True, exist_ok=True)
    SELECTION.write_text(json.dumps(
        {"rule": "lowest mean over (model, h, seed) of val MAE(with lag k) / val MAE(without); exact ties -> shorter lag",
         "selected_lag": best, "mean_ratio": {int(k): float(v) for k, v in mean.items()}, "rows": rows,
         "test_predictions_existed": False, "preregistration_commit": prereg_commit, "provenance": provenance(cfg)}, indent=2))
    L = ["# ACLED lag selection for the rolling check (validation only; generated by scripts/acled_report.py select)", "",
         "Mean over TFT/LSTM × h × seeds of validation MAE(with lag k) / validation MAE(without). No with-run had test "
         "predictions when this was written.", "", "| lag | mean ratio |", "|---:|---:|",
         *[f"| {k} | {v:.4f} |" for k, v in mean.items()], "", f"**Selected lag: {best}**"]
    (SELECTION.with_suffix(".md")).write_text("\n".join(L) + "\n")
    print("\n".join(L))


def report():
    prereg_commit = require_committed(PREREG)
    cfg = load_config(str(ROOT / "configs/model_config.yaml"))
    sel = json.loads((ROOT / "results/selection/selection.json").read_text())["selection"]
    chosen = json.loads(SELECTION.read_text())
    k_star = chosen["selected_lag"]
    cells = {}
    for k in LAGS:
        for m in MODELS:
            for h in HORIZONS:
                c, ref, seeds = sel[f"{m}_sudan_h{h}"]["condition"], baseline(ROOT / "logs/v2/preds", h), []
                for s in SEEDS:
                    key = f"{m}_sudan_h{h}_{c}_s{s}"
                    a = load_run(OUT / f"main/lag{k}/runs", ROOT / f"logs/v2/acled/main/lag{k}/preds", key, ref)
                    b = load_run(ROOT / "results/runs", ROOT / "logs/v2/preds", key, ref)
                    assert a["rec"]["feature_cols"] == b["rec"]["feature_cols"] + conflict_cols(k), key
                    seeds.append({"with": score(ref, a["f"], h), "without": score(ref, b["f"], h),
                                  "with_vs_without": paired(ref, a["f"], b["f"], h),
                                  "monthly_sha256": a["rec"]["config"]["experiment"]["conflict"]["monthly_sha256"]})
                cells[(k, m, h)] = {"lag": k, "model": m, "h": h, "condition": c, "seeds": seeds}
    for loss in LOSSES:
        add_holm([sc["with_vs_without"][loss] for c in cells.values() for sc in c["seeds"]])
    for c in cells.values():
        for loss in LOSSES:
            dms = [sc["with_vs_without"][loss] for sc in c["seeds"]]
            c[f"verdict_{loss}"], c[f"verdict_{loss}_holm"] = verdict(dms, "p_value", WORDS), verdict(dms, "p_holm", WORDS)
    summary = {f"{loss}{suf}": {w: sum(c[f"verdict_{loss}{suf}"] == w for c in cells.values())
                                for w in (*WORDS, "no consistent difference")} for loss in LOSSES for suf in ("", "_holm")}

    # Rolling folds: selected lag, seed 1, pooled over the five test blocks
    rolling = {}
    for m in MODELS:
        for h in HORIZONS:
            c = sel[f"{m}_sudan_h{h}"]["condition"]
            key = f"{m}_sudan_h{h}_{c}_s1"
            pooled = {"y": [], "last": [], "pers": [], "with": [], "without": []}
            per_fold = []
            for j in FOLDS:
                ref = baseline(ROOT / f"logs/v2/rolling/fold{j}/preds", h)
                a = load_run(OUT / f"fold{j}/lag{k_star}/runs", ROOT / f"logs/v2/acled/fold{j}/lag{k_star}/preds", key, ref)
                b = load_run(ROOT / f"results/rolling/fold{j}/runs", ROOT / f"logs/v2/rolling/fold{j}/preds", key, ref)
                assert a["rec"]["feature_cols"] == b["rec"]["feature_cols"] + conflict_cols(k_star), key
                per_fold.append({"fold": j, "mae_with": float(np.abs(ref["y"] - a["f"]).mean()),
                                 "mae_without": float(np.abs(ref["y"] - b["f"]).mean())})
                for name, v in (("y", ref["y"]), ("last", ref["last"]), ("pers", ref["pers"]), ("with", a["f"]), ("without", b["f"])):
                    pooled[name].append(v)
            P = {n: np.concatenate(v) for n, v in pooled.items()}
            pref = {"y": P["y"], "last": P["last"], "pers": P["pers"]}
            rolling[(m, h)] = {"model": m, "h": h, "condition": c, "lag": k_star, "per_fold": per_fold,
                               "with": score(pref, P["with"], h), "without": score(pref, P["without"], h),
                               "with_vs_without": paired(pref, P["with"], P["without"], h),
                               "folds_with_lower_mae": int(sum(f["mae_with"] < f["mae_without"] for f in per_fold))}
    for loss in LOSSES:
        add_holm([r["with_vs_without"][loss] for r in rolling.values()])
    for r in rolling.values():
        for loss in LOSSES:
            r[f"verdict_{loss}"] = verdict([r["with_vs_without"][loss]], "p_value", WORDS)
            r[f"verdict_{loss}_holm"] = verdict([r["with_vs_without"][loss]], "p_holm", WORDS)

    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "acled_results.json").write_text(json.dumps(
        {"provenance": provenance(cfg), "preregistration_commit": prereg_commit, "preregistration_text": PREREG.read_text(),
         "lag_selection": chosen, "summary_main": summary, "main": list(cells.values()), "rolling": list(rolling.values())},
        indent=2, default=float))
    rows = [{"split": "main", "lag": c["lag"], "model": c["model"], "h": c["h"], "seed": s, "loss": loss,
             **{x: sc["with_vs_without"][loss][x] for x in ("dm_hln", "p_value", "p_holm", "n")}}
            for c in cells.values() for s, sc in zip(SEEDS, c["seeds"]) for loss in LOSSES]
    rows += [{"split": "rolling_pooled", "lag": r["lag"], "model": r["model"], "h": r["h"], "seed": 1, "loss": loss,
              **{x: r["with_vs_without"][loss][x] for x in ("dm_hln", "p_value", "p_holm", "n")}}
             for r in rolling.values() for loss in LOSSES]
    pd.DataFrame(rows).to_csv(OUT / "dm_tests.csv", index=False)

    L = ["# ACLED conflict features: with vs without (generated by scripts/acled_report.py report)", "",
         f"Rules fixed in `results/acled/PREREGISTRATION.md` (commit `{prereg_commit[:7]}`) before training. Inputs "
         "log1p political-violence events and fatalities (DISORDER_TYPE definition) of calendar month t − k. TFT and LSTM "
         "under their Phase 3 selected conditions. DM of with vs without (HLN, Newey–West lag h − 1); p per seed with sign "
         "(− = with conflict features has lower loss). Verdict needs the sign to agree and p < 0.05 in all three seeds; "
         "Holm over the 54 seed-level tests. MASE = MAE / MAE(persistence) on the same windows; the last column is the "
         "DM verdict of each arm against persistence (absolute loss, all seeds; descriptive).", "",
         "**Summary, main split (18 cells: help / hurt / no consistent difference):** "
         + "; ".join(f"{k} {' / '.join(str(v[w]) for w in (*WORDS, 'no consistent difference'))}" for k, v in summary.items()), "",
         "| lag | model | h | cond. | MAE with | MAE without | MASE with | MASE without | DM p abs (s1/s2/s3) | verdict abs / Holm | DM p sq | verdict sq / Holm | vs persistence abs: with / without |",
         "|---:|---|---:|---|---:|---:|---:|---:|---|---|---|---|---|"]
    for c in cells.values():
        g = lambda v, x: [sc[v][x] for sc in c["seeds"]]  # noqa: E731
        d = lambda loss: [sc["with_vs_without"][loss] for sc in c["seeds"]]  # noqa: E731
        L.append(f"| {c['lag']} | {c['model']} | {c['h']} | {c['condition']} | {ms(g('with', 'mae'))} | {ms(g('without', 'mae'))} | "
                 f"{ms(g('with', 'mase'), '{:.3f}')} | {ms(g('without', 'mase'), '{:.3f}')} | {pfmt(d('absolute'))} | "
                 f"{c['verdict_absolute']} / {c['verdict_absolute_holm']} | {pfmt(d('squared'))} | "
                 f"{c['verdict_squared']} / {c['verdict_squared_holm']} | {vs_pers([sc['with'] for sc in c['seeds']])} / "
                 f"{vs_pers([sc['without'] for sc in c['seeds']])} |")
    L += ["", f"## Rolling folds 1–5, lag {k_star} (selected on main-split validation: mean ratios "
          + ", ".join(f"lag {k} {v:.4f}" for k, v in chosen["mean_ratio"].items()) + "), seed 1, pooled", "",
          "1 seed per fold; fold test blocks overlap the Phase 3 validation and test periods (as in Phase 4.1).", "",
          "| model | h | pooled MAE with | without | MASE with | without | DM p abs | verdict abs / Holm | DM p sq | verdict sq / Holm | folds with lower MAE | vs persistence abs: with / without |",
          "|---|---:|---:|---:|---:|---:|---|---|---|---|---:|---|"]
    for r in rolling.values():
        L.append(f"| {r['model']} | {r['h']} | {r['with']['mae']:.2f} | {r['without']['mae']:.2f} | {r['with']['mase']:.3f} | "
                 f"{r['without']['mase']:.3f} | {pfmt([r['with_vs_without']['absolute']])} | {r['verdict_absolute']} / "
                 f"{r['verdict_absolute_holm']} | {pfmt([r['with_vs_without']['squared']])} | {r['verdict_squared']} / "
                 f"{r['verdict_squared_holm']} | {r['folds_with_lower_mae']}/5 | {vs_pers([r['with']])} / {vs_pers([r['without']])} |")
    (OUT / "acled_table.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("step", choices=["select", "check", "report"])
    {"select": select, "check": check, "report": report}[ap.parse_args().step]()
