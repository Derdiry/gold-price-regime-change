"""
D1 sensitivity: Sudan baselines under duplicate_date_rule "first" (main) vs "last".

Material change (fixed before looking at the results): relative MAE change
above 5%, or absolute MAPE change of at least 0.1 percentage points.
Writes results/baselines/sensitivity_duplicate_last/comparison.{md,json}.

    python scripts/run_baselines.py --track sudan --duplicate-rule last
    python scripts/compare_duplicate_sensitivity.py
"""

import json
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from src.utils.provenance import provenance  # noqa: E402

MAE_REL, MAPE_ABS = 0.05, 0.1
BASE = Path("results/baselines")
SENS = BASE / "sensitivity_duplicate_last"


def duplicate_dates_per_split() -> dict:
    """Dates with more than one row in new_Data.csv, counted per v2 split row range."""
    raw = pd.read_csv("data/raw/new_Data.csv")
    d = pd.to_datetime(raw["date"], dayfirst=True)
    dup = pd.DatetimeIndex(sorted(d[d.duplicated(keep=False)].unique()))
    info = json.loads((BASE / "sudan_h1.json").read_text())["split_info"]
    out = {}
    for s in ("train", "val", "test"):
        lo, hi = map(pd.Timestamp, info[s]["row_range"])
        out[s] = int(((dup >= lo) & (dup <= hi)).sum())
    return out


def main():
    rows, material = [], []
    for h in (1, 7, 30):
        a = json.loads((BASE / f"sudan_h{h}.json").read_text())
        b = json.loads((SENS / f"sudan_h{h}.json").read_text())
        for name in a["baselines"]:
            for split in ("val", "test"):
                ma, mb = a["baselines"][name][split], b["baselines"][name][split]
                rel = (mb["mae"] - ma["mae"]) / ma["mae"]
                dmape = mb["mape"] - ma["mape"]
                is_mat = abs(rel) > MAE_REL or abs(dmape) >= MAPE_ABS
                cfg_a = a["baselines"][name].get("selected_config")
                cfg_b = b["baselines"][name].get("selected_config")
                rows.append({"h": h, "baseline": name, "split": split,
                             "mae_first": ma["mae"], "mae_last": mb["mae"], "mae_rel_change_pct": 100 * rel,
                             "mape_first": ma["mape"], "mape_last": mb["mape"], "mape_change_pp": dmape,
                             "da_nonzero_first": ma["directional_accuracy_nonzero"],
                             "da_nonzero_last": mb["directional_accuracy_nonzero"],
                             "same_selected_config": cfg_a == cfg_b, "material": is_mat})
                if is_mat:
                    material.append(f"h={h} {name} {split}")
    dups = duplicate_dates_per_split()
    out = {"provenance": provenance({"mlflow": {"protocol": "v2"}}),
           "threshold": {"mae_rel": MAE_REL, "mape_abs_pp": MAPE_ABS},
           "duplicate_dates_per_split": dups, "rows": rows, "material_changes": material}
    (SENS / "comparison.json").write_text(json.dumps(out, indent=2))
    max_rel = max(abs(r["mae_rel_change_pct"]) for r in rows)
    max_mape = max(abs(r["mape_change_pp"]) for r in rows)
    lines = ["# Sensitivity of the Sudan baselines to the duplicate-date rule (first vs last)", "",
             "Generated by scripts/compare_duplicate_sensitivity.py. Material = relative MAE change "
             f"> {100 * MAE_REL:.0f}% or |ΔMAPE| ≥ {MAPE_ABS} pp (fixed in advance).", "",
             f"Dates with more than one row, by split row range: train {dups['train']}, "
             f"val {dups['val']}, test {dups['test']}.", "",
             f"**Material changes: {len(material)}** " + (f"({', '.join(material)})" if material else "")
             + f". Largest |ΔMAE| = {max_rel:.2f}%, largest |ΔMAPE| = {max_mape:.3f} pp.", "",
             "| h | baseline | split | MAE first | MAE last | ΔMAE % | MAPE first | MAPE last | ΔMAPE pp | DA non-zero first | DA non-zero last | same setting |",
             "|---:|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---|"]
    for r in rows:
        lines.append(f"| {r['h']} | {r['baseline']} | {r['split']} | {r['mae_first']:.2f} | {r['mae_last']:.2f} | "
                     f"{r['mae_rel_change_pct']:+.2f} | {r['mape_first']:.3f} | {r['mape_last']:.3f} | "
                     f"{r['mape_change_pp']:+.3f} | {r['da_nonzero_first']:.1f} | {r['da_nonzero_last']:.1f} | "
                     f"{'yes' if r['same_selected_config'] else 'no'} |")
    (SENS / "comparison.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines[:8]))


if __name__ == "__main__":
    main()
