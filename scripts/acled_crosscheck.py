"""
Phase 4.3 step 1: build the monthly Sudan ACLED series from the weekly Africa
file and cross-check it against the country-month-year file.

Outputs:
  logs/v2/acled/sudan_monthly_{definition}_{rule}.csv  monthly series (gitignored: ACLED-derived)
  logs/v2/acled/crosscheck_by_month.csv             per-month comparison (gitignored)
  results/acled/crosscheck.{json,md}                summary statistics and flagged months (diffs only)

    python scripts/acled_crosscheck.py
"""

import hashlib
import json
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from src.data.acled import (DEFINITIONS, POLITICAL_VIOLENCE, crosscheck, load_monthly_cmy_sudan, load_weekly_sudan,  # noqa: E402
                            monthly_series, n_weeks_spanning_two_months)
from src.data.fetchers import load_config  # noqa: E402
from src.utils.provenance import provenance  # noqa: E402

RAW = ROOT / "data/raw/sudan"
WEEKLY = RAW / "Africa_aggregated_data_up_to_week_of-2026-10-17.xlsx"
CMY = RAW / "number_of_political_violence_events_by_country-month-year_as-of-23Oct2026.xlsx"
START, END = "2014-10", "2022-12"
PRIVATE, OUT = ROOT / "logs/v2/acled", ROOT / "results/acled"


def sha256(p):
    return hashlib.sha256(p.read_bytes()).hexdigest()


AGGREGATE_KEYS = ("months", "pearson_r", "mean_abs_diff", "total_built", "total_cmy", "n_months_over_tol", "tol_pct")


def main():
    PRIVATE.mkdir(parents=True, exist_ok=True)
    OUT.mkdir(parents=True, exist_ok=True)
    weekly = load_weekly_sudan(WEEKLY)
    cmy = load_monthly_cmy_sudan(CMY)
    in_period = weekly[(weekly["WEEK"] >= pd.Timestamp(START + "-01") - pd.Timedelta(days=6))
                       & (weekly["WEEK"] <= pd.Timestamp(END + "-31"))]

    built = {(d, r): monthly_series(weekly, r, d) for d in DEFINITIONS for r in ("prorata", "start")}
    for (d, r), m in built.items():
        m.to_csv(PRIVATE / f"sudan_monthly_{d}_{r}.csv", index_label="month")   # same files as src/data/acled.cached_monthly
    checks = {"primary (DISORDER_TYPE contains 'Political violence', prorata)":
              crosscheck(built[("disorder_type", "prorata")]["pv_events"], cmy, START, END),
              "sensitivity (DISORDER_TYPE, week start)": crosscheck(built[("disorder_type", "start")]["pv_events"], cmy, START, END),
              "sensitivity (3 event types, prorata)": crosscheck(built[("event_types", "prorata")]["pv_events"], cmy, START, END),
              "sensitivity (3 event types, week start)": crosscheck(built[("event_types", "start")]["pv_events"], cmy, START, END)}
    idx = pd.period_range(START, END, freq="M")
    pd.DataFrame({"cmy": cmy.reindex(idx), **{f"{d}_{r}": m["pv_events"].reindex(idx) for (d, r), m in built.items()}}
                 ).to_csv(PRIVATE / "crosscheck_by_month.csv", index_label="month")

    info = {"weekly_file": WEEKLY.name, "weekly_sha256": sha256(WEEKLY), "cmy_file": CMY.name, "cmy_sha256": sha256(CMY),
            "period": [START, END], "political_violence_primary": "DISORDER_TYPE contains 'Political violence'",
            "political_violence_event_types_sensitivity": POLITICAL_VIOLENCE,
            "weekly_sudan_rows": int(len(weekly)), "weekly_rows_in_period": int(len(in_period)),
            "weeks_in_period": int(in_period["WEEK"].nunique()),
            "weeks_in_period_spanning_two_months": n_weeks_spanning_two_months(in_period),
            "admin1_in_period": sorted(in_period["ADMIN1"].unique()),
            "event_types_in_period": in_period.groupby("EVENT_TYPE")["EVENTS"].sum().astype(int).to_dict()}
    cfg = load_config(str(ROOT / "configs/model_config.yaml"))
    (OUT / "crosscheck.json").write_text(json.dumps(
        {"provenance": provenance(cfg), "info": info,
         "checks": {k: {kk: vv for kk, vv in v.items() if kk in AGGREGATE_KEYS}
                    for k, v in checks.items()}}, indent=2))

    L = ["# ACLED Sudan: weekly build vs country-month-year file (generated by scripts/acled_crosscheck.py)", "",
         f"Weekly file `{WEEKLY.name}` (SHA-256 `{info['weekly_sha256'][:12]}…`); country-month-year file `{CMY.name}` "
         f"(SHA-256 `{info['cmy_sha256'][:12]}…`). Both gitignored; monthly values stay in `logs/v2/acled/` and are not committed.", "",
         f"Country = exactly \"Sudan\". Period {START} → {END}: {info['weeks_in_period']} weeks, "
         f"{info['weeks_in_period_spanning_two_months']} of them span two months. Political violence (primary, ACLED's "
         "own definition, author decision 2026-10-31) = DISORDER_TYPE contains \"Political violence\"; sensitivity = "
         f"EVENT_TYPE in {', '.join(POLITICAL_VIOLENCE)}, which omits \"Excessive force against protesters\" and "
         "\"Mob violence\".", "",
         f"Admin1 kept in the period ({len(info['admin1_in_period'])}): {', '.join(info['admin1_in_period'])}.", "",
         "| build | months | Pearson r | mean abs diff | total built / file | months > 5% off |",
         "|---|---:|---:|---:|---|---:|"]
    for k, c in checks.items():
        L.append(f"| {k} | {c['months']} | {c['pearson_r']:.4f} | {c['mean_abs_diff']:.2f} "
                 f"| {c['total_built']:.0f} / {c['total_cmy']:.0f} | {c['n_months_over_tol']} |")
    L += ["", "Only aggregate statistics are published. Per-month values and per-month differences are "
          "derived from ACLED data and stay in `logs/v2/acled/` (not committed)."]
    (OUT / "crosscheck.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
