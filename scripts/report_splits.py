"""
Report the v2 train/val/test date ranges and window counts for every
(track, horizon), the data-quality corrections, and the window counts of the
original setup for comparison. Writes results/data/split_summary.{json,md}. No training.

    python scripts/report_splits.py
"""

import json
import logging
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from src.data.dataset import make_dataset
from src.data.features import GLOBAL_FEATURE_COLS, SUDAN_FEATURE_COLS
from src.data.fetchers import load_config
from src.data.pipeline import build_global, build_sudan
from src.utils.provenance import provenance

logging.basicConfig(level=logging.WARNING, format="%(levelname)s | %(name)s | %(message)s")

# Longest feature lookback (sma_200); rows this close after the long gap still
# carry rolling features computed partly from forward-filled gap days.
LONGEST_LOOKBACK = 200


def v1_counts(track: str, horizon: int) -> dict | None:
    """Window counts of the original-setup sequences, if their .npz files are still on disk."""
    p = Path(f"data/features/{track}_h{horizon}.npz")
    if not p.exists():
        return None
    z = np.load(p)
    return {s: int(z[f"X_{s}"].shape[0]) for s in ("train", "val", "test")}


def main():
    cfg = load_config("configs/model_config.yaml")
    data = {"global": build_global(cfg), "sudan": build_sudan(cfg)}
    manifests = {t: json.loads((Path(cfg["paths"]["processed_data"]) / f"data_manifest_{t}.json").read_text())
                 for t in data}

    gap_end = None
    for g in manifests["sudan"]["quality"]["fill_flags"]["long_gaps"]:
        gap_end = pd.Timestamp(g["next_observed"])

    rows = []
    for track, df in data.items():
        cols = GLOBAL_FEATURE_COLS if track == "global" else SUDAN_FEATURE_COLS
        target = cfg["data"]["global_target_col"] if track == "global" else cfg["data"]["target_col"]
        for h in cfg["sequence"]["horizons"]:
            splits, _, _, info = make_dataset(df, cfg, track, h, cols, target, save=False)
            v1 = v1_counts(track, h)
            for s in ("train", "val", "test"):
                rec = {"track": track, "horizon": h, "split": s, **info[s],
                       "v1_windows": v1[s] if v1 else None}
                if track == "sudan" and gap_end is not None:
                    ctx_start = pd.to_datetime(splits[f"origin_{s}"]) - pd.Timedelta(days=cfg["sequence"]["input_length"] - 1)
                    rec["windows_with_features_near_gap"] = int(
                        ((ctx_start >= gap_end) & (ctx_start < gap_end + pd.Timedelta(days=LONGEST_LOOKBACK))).sum())
                rows.append(rec)

    out_dir = Path(cfg["paths"]["results"]) / "data"
    out_dir.mkdir(parents=True, exist_ok=True)
    summary = {"provenance": provenance(cfg), "splits": rows,
               "quality": {"sudan": manifests["sudan"]["quality"]},
               "inputs": {t: m["inputs"] for t, m in manifests.items()}}
    (out_dir / "split_summary.json").write_text(json.dumps(summary, indent=2, default=str))

    q = manifests["sudan"]["quality"]
    lines = ["# v2 splits and windows (generated by scripts/report_splits.py)", "",
             f"git_commit: `{summary['provenance']['git_commit']}`", "",
             "## Sudan data-quality corrections", "",
             f"- Decimal-shift fixes: {len(q['decimal_shift_fixes'])} "
             + "; ".join(f"{f['date']} {f['column']} {f['old']:g} -> {f['new']:g}" for f in q["decimal_shift_fixes"]),
             f"- Duplicate dates: {q['duplicate_dates']['dates_with_multiple_rows']} dates with >1 row; "
             f"rule `{q['duplicate_dates']['rule']}` keeps {q['duplicate_dates']['unique_dates']} of "
             f"{q['duplicate_dates']['file_rows']} file rows",
             f"- Daily rows: {q['fill_flags']['daily_rows']}, of which forward-filled: {q['fill_flags']['ffilled_days']}",
             *[f"- Long gap: last observed {g['last_observed']}, next {g['next_observed']} ({g['days']} days); "
               f"{g['flagged_days']} daily rows flagged `in_long_gap`" for g in q["fill_flags"]["long_gaps"]],
             "", "## Windows per split", "",
             "| track | h | split | rows (date range) | forecast origins | target dates | windows v2 | dropped | original-setup windows | ctx starts <200d after gap |",
             "|---|---:|---|---|---|---|---:|---:|---:|---:|"]
    for r in rows:
        tr = r["target_range"] or ["—", "—"]
        lines.append(
            f"| {r['track']} | {r['horizon']} | {r['split']} | {r['rows']} ({r['row_range'][0]} → {r['row_range'][1]}) "
            f"| {r['first_origin']} → {r['last_origin']} | {tr[0]} → {tr[1]} | {r['windows']} | {r['windows_dropped']} "
            f"| {r['v1_windows'] if r['v1_windows'] is not None else '—'} | {r.get('windows_with_features_near_gap', '—')} |")
    (out_dir / "split_summary.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
