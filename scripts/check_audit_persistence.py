"""
Independent check of the version audit's persistence finding.

The audit (2026-10-28) reported naive-persistence test MAPE on the test
windows of the original MinMax setup and said it beats every model of that setup.
This study keeps the same test windows, so this compares the persistence
baseline (results/baselines/) with
  (a) the persistence MAPE quoted in the audit (the claim being checked), and
  (b) the best original-setup model/ensemble MAPE in data/processed/metrics_*.csv
      (those numbers are not results of this study; they appear only as the claim under test).
Writes results/baselines/audit_persistence_check.md.
"""

import json
from pathlib import Path

import pandas as pd

# Quoted from version-audit-report.md §3 ("New, computed during this audit")
AUDIT_PERSISTENCE_MAPE = {("sudan", 1): 0.33, ("sudan", 7): 1.12, ("sudan", 30): 3.23,
                          ("global", 1): 0.68, ("global", 7): 1.34, ("global", 30): 2.58}

lines = ["# Check of the audit's persistence finding (generated by scripts/check_audit_persistence.py)", "",
         "| track | h | persistence MAPE % (this study) | audit's persistence MAPE % | agrees (2 dp) | best original-setup model (data/processed CSV) | its MAPE % | ratio original best / persistence | same test windows as the original setup |",
         "|---|---:|---:|---:|---|---|---:|---:|---|"]
for (track, h), quoted in AUDIT_PERSISTENCE_MAPE.items():
    r = json.loads(Path(f"results/baselines/{track}_h{h}.json").read_text())
    p = r["baselines"]["persistence"]["test"]["mape"]
    v1 = pd.read_csv(f"data/processed/metrics_{track}_h{h}.csv")
    best = v1.loc[v1["mape"].idxmin()]
    v1_windows = {"sudan": {1: 437, 7: 431, 30: 408}, "global": {1: 917, 7: 911, 30: 888}}[track][h]
    lines.append(f"| {track} | {h} | {p:.2f} | {quoted:.2f} | {'yes' if round(p, 2) == quoted else 'NO'} | "
                 f"{best['model']} | {best['mape']:.2f} | {best['mape'] / p:.1f}× | "
                 f"{'yes' if r['windows']['test'] == v1_windows else 'NO'} |")
Path("results/baselines/audit_persistence_check.md").write_text("\n".join(lines) + "\n")
print("\n".join(lines))
