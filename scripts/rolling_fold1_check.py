"""
Phase 4.1 follow-up (post hoc, not preregistered): Sudan h=30 fold 1, where
ARIMA/ETS/VECM have MASE about 3.8 against about 1.0 in folds 2-5.

Writes results/rolling/fold1_sudan_h30_check.{md,json}: per-fold block path,
persistence MAE, the baseline settings chosen on fold validation, the sign of
the baseline errors, and the Sudan h=30 pooled scores with folds 1-5 and 2-5.

    python scripts/rolling_fold1_check.py
"""

import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "scripts"))
from rolling_report import BASELINES, LOSSES, MODELS, score, verdict  # noqa: E402
from run_baselines import build_sudan  # noqa: E402
from src.data.fetchers import load_config  # noqa: E402
from src.models.ensemble import apply_ensemble, fit_validation_ensemble  # noqa: E402
from src.utils.provenance import provenance  # noqa: E402

TRACK, H, FOLDS = "sudan", 30, [1, 2, 3, 4, 5]
OUT = ROOT / "results/rolling"


def load_fold(k, sel):
    """Test targets, origin prices, persistence and every forecast of fold k (as in rolling_report.py)."""
    pdir = ROOT / f"logs/v2/rolling/fold{k}/preds"
    b = np.load(pdir / "baselines" / f"{TRACK}_h{H}.npz")
    fv, ft = {}, {}
    for m in MODELS:
        z = np.load(pdir / f"{m}_{TRACK}_h{H}_{sel[f'{m}_{TRACK}_h{H}']['condition']}_s1.npz")
        fv[m], ft[m] = z["val_pred"], z["test_pred"]
    ft["ensemble"] = apply_ensemble(ft, fit_validation_ensemble(fv, b["y_val"], top_n=2))
    for n in BASELINES[TRACK]:
        ft[n] = b[f"{n}_test"]
    return b["y_test"], b["last_test"], b["persistence_test"], ft


def pooled(folds, data):
    Y, Lst, P = (np.concatenate([data[k][i] for k in folds]) for i in range(3))
    out = {}
    for n in data[folds[0]][3]:
        r = score(Y, np.concatenate([data[k][3][n] for k in folds]), Lst, P, H)
        out[n] = {"mae": r["mae"], "mase": r["mase"], "n": r["n"],
                  **{f"p_{loss}": r[f"dm_{loss}"]["p_value"] for loss in LOSSES},
                  **{f"verdict_{loss}": verdict(r[f"dm_{loss}"]) if n != "persistence" else "—" for loss in LOSSES}}
    return out


def main():
    cfg = load_config(str(ROOT / "configs/model_config.yaml"))
    sel = json.loads((ROOT / "results/selection/selection.json").read_text())["selection"]
    df = build_sudan(cfg)
    price = df[cfg["data"]["target_col"]]
    gap_end = int(np.where(df["in_long_gap"].to_numpy() == 1)[0][-1])

    blocks, data = [], {}
    for k in FOLDS:
        rec = json.loads((OUT / f"fold{k}/baselines/{TRACK}_h{H}.json").read_text())
        si, bl = rec["split_info"], rec["baselines"]
        y, last, pers, ft = data[k] = load_fold(k, sel)
        row = {"fold": k, "val": si["val"]["row_range"], "test": si["test"]["row_range"],
               "first_val_origin_rows_after_gap": int(df.index.get_loc(pd.Timestamp(si["val"]["first_origin"]))) - gap_end,
               "persistence_val_mae": bl["persistence"]["val"]["mae"], "persistence_test_mae": bl["persistence"]["test"]["mae"],
               "actual_mean_change_step30": float((y[:, -1] - last).mean())}
        for s in ("val", "test"):
            a, b = si[s]["row_range"]
            p = price[a:b]
            row[f"{s}_block_change_pct"] = float(100 * (p.iloc[-1] / p.iloc[0] - 1))
        for n in ("arima", "ets", "vecm"):
            e = ft[n] - y
            row[n] = {"selected": bl[n]["selected_config"], "test_mase": float(np.abs(e).mean() / np.abs(pers - y).mean()),
                      "mean_signed_error": float(e.mean()), "share_windows_over": float((e.mean(1) > 0).mean()),
                      "mean_forecast_change_step30": float((ft[n][:, -1] - last).mean())}
        blocks.append(row)

    sens = {"folds_1_5": pooled(FOLDS, data), "folds_2_5": pooled(FOLDS[1:], data)}
    ref = json.loads((OUT / "rolling_results.json").read_text())["results"][f"{TRACK}_h{H}"]["pooled"]
    for n, r in sens["folds_1_5"].items():
        assert np.isclose(r["mae"], ref[n]["mae"], rtol=1e-9), f"{n}: folds 1-5 do not reproduce rolling_results.json"
    (OUT / "fold1_sudan_h30_check.json").write_text(json.dumps(
        {"provenance": provenance(cfg), "post_hoc": True, "gap_end_row": str(df.index[gap_end].date()),
         "blocks": blocks, "sensitivity": sens}, indent=2, default=str))

    L = ["# Sudan h=30, fold 1 check (post hoc, generated by scripts/rolling_fold1_check.py)", "",
         "Not preregistered. Explains the fold-1 MASE of ARIMA/ETS/VECM and gives the pooled scores without fold 1. "
         "The preregistered verdicts in `rolling_table.md` stand unchanged.", "",
         f"Last gap row: {df.index[gap_end].date()}. Context length L = {cfg['sequence']['input_length']}.", "",
         "| fold | val block | val change | test block | test change | first val origin, rows after gap | persistence MAE val / test | actual mean 30-step change | ARIMA / ETS / VECM selected | their test MASE | mean signed error | windows over-forecast | mean forecast 30-step change |",
         "|---:|---|---:|---|---:|---:|---|---:|---|---|---|---|---|"]
    for r in blocks:
        cfgs = " / ".join(json.dumps(r[n]["selected"]).replace('"', "") for n in ("arima", "ets", "vecm"))
        fmt = lambda key, f: " / ".join(f % r[n][key] for n in ("arima", "ets", "vecm"))  # noqa: E731
        L.append(f"| {r['fold']} | {r['val'][0]} → {r['val'][1]} | {r['val_block_change_pct']:+.1f}% | {r['test'][0]} → {r['test'][1]} | "
                 f"{r['test_block_change_pct']:+.1f}% | {r['first_val_origin_rows_after_gap']} | {r['persistence_val_mae']:.0f} / {r['persistence_test_mae']:.0f} | "
                 f"{r['actual_mean_change_step30']:+.0f} | {cfgs} | {fmt('test_mase', '%.2f')} | {fmt('mean_signed_error', '%+.0f')} | "
                 f"{fmt('share_windows_over', '%.2f')} | {fmt('mean_forecast_change_step30', '%+.0f')} |")
    L += ["", "## Sudan h=30 pooled, folds 1–5 vs folds 2–5", "",
          "| configuration | MAE 1–5 | MASE 1–5 | verdict abs / sq 1–5 | MAE 2–5 | MASE 2–5 | DM p abs / sq 2–5 | verdict abs / sq 2–5 |",
          "|---|---:|---:|---|---:|---:|---|---|"]
    a, b = sens["folds_1_5"], sens["folds_2_5"]
    for n in a:
        if n == "persistence":
            L.append(f"| *persistence* | {a[n]['mae']:.2f} | 1.000 | — | {b[n]['mae']:.2f} | 1.000 | — | — |")
            continue
        label = n if n in MODELS + ["ensemble"] else f"*{n}*"
        L.append(f"| {label} | {a[n]['mae']:.2f} | {a[n]['mase']:.3f} | {a[n]['verdict_absolute']} / {a[n]['verdict_squared']} | "
                 f"{b[n]['mae']:.2f} | {b[n]['mase']:.3f} | {b[n]['p_absolute']:.3f} / {b[n]['p_squared']:.3f} | "
                 f"{b[n]['verdict_absolute']} / {b[n]['verdict_squared']} |")
    L += ["", f"Windows: {a['persistence']['n']} (folds 1–5), {b['persistence']['n']} (folds 2–5)."]
    (OUT / "fold1_sudan_h30_check.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
