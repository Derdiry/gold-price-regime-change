"""
Reuse check for Phases 4.3 and 4.4: are the reused runs' data byte-identical
to what the current code builds, and is their training configuration
unchanged?

Inputs: fingerprint files from scripts/dataset_fingerprint.py, one per commit.
Output: results/provenance/reuse_fingerprints.{json,md}; exit 1 on any mismatch.

    python scripts/compare_fingerprints.py --head fp_HEAD.json --ref <commit>=fp.json ...
"""

import argparse
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "results/provenance"


def git(*a):
    return subprocess.run(["git", *a], cwd=ROOT, capture_output=True, text=True, check=True).stdout.strip()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--head", required=True)
    ap.add_argument("--ref", nargs="+", required=True, help="commit=fingerprint.json")
    args = ap.parse_args()
    head = json.loads(Path(args.head).read_text())
    head_commit = git("rev-parse", "HEAD")
    sys.path.insert(0, str(ROOT))
    import train  # noqa: E402  (no-flag feature list exactly as train.py builds it)
    from src.data.features import SUDAN_FEATURE_COLS
    from src.data.fetchers import load_config
    cfg = load_config(str(ROOT / "configs/model_config.yaml"))
    import pandas as pd
    no_flag = train.feature_list_for(cfg, "sudan", cfg["data"]["target_col"], pd.DataFrame(columns=SUDAN_FEATURE_COLS))
    checks = {"no-flag feature list == SUDAN_FEATURE_COLS": no_flag == list(SUDAN_FEATURE_COLS)}
    rows, ok = [], all(checks.values())
    for spec in args.ref:
        commit, path = spec.split("=")
        ref = json.loads(Path(path).read_text())
        cfg_same = not git("diff", commit, head_commit, "--", "configs/model_config.yaml")
        code_same = not git("diff", commit, head_commit, "--", "src/models", "src/training")
        raw_same = git("rev-parse", f"{commit}:data/raw/new_Data.csv") == git("rev-parse", f"{head_commit}:data/raw/new_Data.csv")
        for key, arrays in ref["arrays"].items():
            diff = sorted(k for k in arrays if head["arrays"][key].get(k) != arrays[k])
            same = not diff and set(arrays) == set(head["arrays"][key])
            ok &= same and cfg_same and raw_same and code_same
            rows.append({"commit": commit, "setting": key, "arrays": len(arrays), "identical": same, "differing": diff,
                         "config_unchanged": cfg_same, "raw_csv_blob_unchanged": raw_same,
                         "model_and_trainer_code_unchanged": code_same})
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "reuse_fingerprints.json").write_text(json.dumps(
        {"head": head_commit, "checks": checks, "all_identical": ok, "rows": rows, "head_fingerprints": head["arrays"]}, indent=2))
    L = ["# Reuse check: data seen by reused runs vs current code (generated by scripts/compare_fingerprints.py)", "",
         f"HEAD `{head_commit[:7]}`. Each setting hashes every array a Sudan model sees (inputs, targets, price-unit "
         "targets, target contexts, origin prices, origin dates, feature list), built by `scripts/dataset_fingerprint.py` "
         "inside a git worktree of the commit that trained the reused run, and at HEAD with no variant flag.", "",
         *[f"- {k}: **{'yes' if v else 'NO'}**" for k, v in checks.items()], "",
         "| commit | setting | arrays | byte-identical | config file unchanged | raw CSV blob unchanged | src/models, src/training unchanged |",
         "|---|---|---:|---|---|---|---|"]
    L += [f"| `{r['commit']}` | {r['setting']} | {r['arrays']} | {'yes' if r['identical'] else 'NO: ' + ', '.join(r['differing'])} | "
          f"{'yes' if r['config_unchanged'] else 'NO'} | {'yes' if r['raw_csv_blob_unchanged'] else 'NO'} | "
          f"{'yes' if r['model_and_trainer_code_unchanged'] else 'NO'} |" for r in rows]
    L += ["", f"**All identical: {'yes' if ok else 'NO'}**"]
    (OUT / "reuse_fingerprints.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))
    sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()
